"""Executable, dataset-driven comparison runner for V1 through V4.

The input is a JSON file with a ``populations`` array. Each population must
contain ``seekers``, ``candidates``, optional ``interactions`` and
``mentorships``, and ``relevantBySeeker`` mapping seeker IDs to relevant IDs.
No population or relevance label is generated by this runner.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path
from typing import Any

from .engine import RecommendationError, recommend
from .evaluation import evaluate_runs
from .model_loader import ModelLoadError, load_v4_model

VERSIONS = ("v1", "v2.0", "v2.1", "v2.2", "v2.3", "v2.4", "v3", "v4")


def _unavailable(dataset: Path, reason: str) -> dict[str, Any]:
    return {"status": "unavailable", "dataset": str(dataset), "reason": reason}


def run_experiments(dataset_path: str | Path, output_dir: str | Path, seeds: list[int]) -> dict[str, Any]:
    dataset = Path(dataset_path)
    if not dataset.is_file():
        return _unavailable(dataset, "dataset file was not found; no experiment was run")
    try:
        payload = json.loads(dataset.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return _unavailable(dataset, f"dataset could not be read: {exc}")
    populations = payload.get("populations")
    if not isinstance(populations, list) or not populations:
        return _unavailable(dataset, "dataset must contain a non-empty populations array")

    results: dict[str, Any] = {
        "status": "completed",
        "dataset": str(dataset),
        "seeds": seeds,
        "versions": {},
        "populations": len(populations),
    }
    model = None
    version_errors: dict[str, str] = {}
    try:
        if "v4" in VERSIONS:
            model = load_v4_model()
    except ModelLoadError as exc:
        version_errors["v4"] = str(exc)

    rows: list[dict[str, Any]] = []
    for version in VERSIONS:
        if version in version_errors:
            results["versions"][version] = {"status": "unavailable", "reason": version_errors[version]}
            continue
        all_runs: list[dict[str, Any]] = []
        try:
            for seed in seeds:
                rankings: dict[str, list[dict[str, Any]]] = {}
                for population in populations:
                    interactions = population.get("interactions", [])
                    mentorships = population.get("mentorships", [])
                    for seeker in population.get("seekers", []):
                        options = {
                            "seed": seed,
                            "now": population.get("now"),
                            "limit": 10,
                            "weightProfile": population.get("weightProfile", "internal"),
                        }
                        if version == "v4":
                            options["model"] = model
                        result = recommend(
                            seeker=seeker,
                            candidates=population.get("candidates", []),
                            interactions=interactions,
                            mentorships=mentorships,
                            version=version,
                            options=options,
                        )
                        seeker_id = str(seeker.get("id") or seeker.get("_id"))
                        rankings[seeker_id] = [
                            {"id": item["id"], "score": item["score"], "scoreRaw": item["scoreRaw"]}
                            for item in result["recommendations"]
                        ]
                all_runs.append({"seed": seed, "rankings": rankings})
            relevant = {
                str(key): set(map(str, value))
                for population in populations
                for key, value in population.get("relevantBySeeker", {}).items()
            }
            metrics = evaluate_runs(all_runs, relevant)
            results["versions"][version] = {"status": "completed", "metrics": metrics, "runs": all_runs}
            for metric, value in metrics.items():
                if isinstance(value, (int, float)):
                    rows.append({"version": version, "metric": metric, "value": value})
        except (KeyError, TypeError, RecommendationError, ValueError) as exc:
            results["versions"][version] = {"status": "unavailable", "reason": str(exc)}
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    (output / "experiment-results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    with (output / "experiment-results.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=["version", "metric", "value"])
        writer.writeheader()
        writer.writerows(rows)
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description="Run MentorConnect V1-V4 experiments without fabricating data")
    parser.add_argument("--dataset", required=True, help="JSON dataset containing populations and relevance labels")
    parser.add_argument("--output-dir", default="research/out/python", help="Directory for CSV and JSON output")
    parser.add_argument("--seeds", default="11,23,37,41,59", help="Comma-separated fixed seeds")
    args = parser.parse_args()
    result = run_experiments(args.dataset, args.output_dir, [int(seed) for seed in args.seeds.split(",") if seed])
    print(json.dumps({
        "status": result["status"],
        "dataset": result["dataset"],
        "versions": {key: value["status"] for key, value in result.get("versions", {}).items()},
    }, indent=2))
    return 0 if result["status"] == "completed" else 2


if __name__ == "__main__":
    sys.exit(main())
